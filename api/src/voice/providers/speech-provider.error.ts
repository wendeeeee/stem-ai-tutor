export type SpeechProviderFailureCode =
  | 'SPEECH_NOT_CONFIGURED'
  | 'SPEECH_APPLICATION_TIMEOUT'
  | 'SPEECH_PROVIDER_TIMEOUT'
  | 'SPEECH_PROVIDER_NETWORK_ERROR'
  | 'SPEECH_PROVIDER_AUTHENTICATION_FAILED'
  | 'SPEECH_PROVIDER_RATE_LIMITED'
  | 'SPEECH_PROVIDER_VALIDATION_FAILED'
  | 'SPEECH_PROVIDER_INFERENCE_REJECTED'
  | 'SPEECH_PROVIDER_BAD_GATEWAY'
  | 'SPEECH_PROVIDER_UNAVAILABLE'
  | 'SPEECH_PROVIDER_GATEWAY_TIMEOUT'
  | 'SPEECH_PROVIDER_HTTP_ERROR'
  | 'SPEECH_PROVIDER_UNSUPPORTED_CONTENT_TYPE'
  | 'SPEECH_PROVIDER_EMPTY_RESPONSE'
  | 'SPEECH_PROVIDER_RESPONSE_TOO_LARGE'
  | 'SPEECH_PROVIDER_INVALID_AUDIO';

export class SpeechProviderError extends Error {
  constructor(
    readonly code: SpeechProviderFailureCode,
    readonly retryable: boolean,
  ) {
    super(code);
    this.name = 'SpeechProviderError';
  }
}
